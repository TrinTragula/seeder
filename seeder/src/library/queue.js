import { VERSIONS } from '../util/constants';

/**
 * Candidate-space limits of the streaming seed search.
 * DEFAULT_MAX_SCAN caps how many candidates one findSeeds() call may consume;
 * MASK48 isolates the lower-48 "structure family" a seed belongs to.
 */
export const DEFAULT_MAX_SCAN = 50_000_000n;
export const MASK48 = (1n << 48n) - 1n;

// Where each candidate space ends: structure candidates are lower-48 families,
// biome candidates are signed 64-bit seeds counted upwards from the start seed.
const FAMILY_SPACE_END = 1n << 48n;
const SEED_SPACE_END = 1n << 63n;

const MIN_SHARD = 8;
const MAX_SHARD = 250_000;
// Cost of one checkForBiomes() per 1:4 cell on the noise generators, in µs (measured):
// 2.7 for the 1.18+ Overworld, 0.13 for the Nether (1.16+), 1.7 for the End (a full
// 150×150 End check costs ~38 ms on every version with the End generator).
const CELL_COST_US = { overworld: 2.7, nether: 0.13, end: 1.7 };

// Consecutive boot crashes (a worker dying before DONE_LOADING, e.g. a failed
// importScripts) tolerated before crashed workers stop being replaced.
const MAX_BOOT_FAILURES = 3;
const crashError = (message) => ({ code: 'WORKER_CRASH', message });

const bigMin = (...values) => values.reduce((a, b) => (b < a ? b : a));
const clampShard = (n) => Math.min(MAX_SHARD, Math.max(MIN_SHARD, Math.round(n)));

/**
 * How many candidates one FIND_SEEDS shard covers, from a ~1 s cost model: a worker
 * stuck in the synchronous C loop cannot see messages, so a shard is the unit of
 * waste on STOP and of accounting on resume, and it should not outlive a second.
 *   - structure modes: 250 000 families, even with several types (Village + Mansion
 *     ±300 is ~14 s per shard when hits are sparse): STOP is a terminate anyway and the
 *     tails skipped on resume don't matter in a 2^48-family space, so a smaller shard
 *     would only add message round trips.
 *   - Nether / End biome-only: cells² × per-cell cost, whatever the version - the 1.16+
 *     Nether noise costs the same on 1.16.5, 1.17 and 26.3 (~300 seeds/s at ±300), the
 *     End generator likewise (~38 ms per full ±300 check); before those versions the
 *     dimension holds a single biome, so every seed hits and the shard length is moot
 *   - Overworld biome-only up to 1.17: 10 000 (layer stacks, microseconds per check)
 *   - Overworld biome-only 1.18+: cells² × 2.7 µs → ±100 ≈ 150, ±300 ≈ 16, ±500 ≈ 5 (floor 8)
 * Nether ±300 → 342, End ±300 → 26 (±1000 → 8).
 */
export function shardLenFor(criteria) {
    const { mcVersion, dimension = 0, rangeBlocks = 300, structures = [] } = criteria;
    if (structures.length > 0) return MAX_SHARD;
    const cells = 2 * Math.ceil(rangeBlocks / 4);
    if (dimension === -1) return clampShard(1e6 / (cells * cells * CELL_COST_US.nether));
    if (dimension === 1) return clampShard(1e6 / (cells * cells * CELL_COST_US.end));
    if (mcVersion <= VERSIONS['1.17']) return 10_000;
    return clampShard(1e6 / (cells * cells * CELL_COST_US.overworld));
}

export class QueueManager {
    constructor(path, numberOfWorkers) {
        this.path = path;
        this.numberOfWorkers = numberOfWorkers ?? navigator.hardwareConcurrency ?? 1;
        this.workers = [];
        // Spawned but not loaded yet: a worker joins `workers` on DONE_LOADING. Tracked
        // so killAll() can also tear down a pool (or a replacement) that is still booting.
        this.booting = new Set();
        this.workerCounter = 0;
        this.bootFailures = 0;
        // Set by _poolDead (every worker crashed while booting): the WORKER_CRASH error that
        // answers everything asked from then on, since no worker will ever run it.
        this.poolError = null;
        this.COLORS = null;
        // Tile scheduling: FIFO of pending GET_AREA jobs + a set of in-flight
        // request keys so the same tile is never generated twice concurrently.
        this.pending = [];
        this.inFlight = new Set();
        // One-shot requests (see request()): FIFO queues per priority. Entries leave
        // them when posted or cancelled; a posted entry lives on its worker (`worker.request`).
        this.highQueue = [];
        this.lowQueue = [];
        this._requestCounter = 0;
        // The active streaming seed search (see findSeeds), or null.
        this.search = null;
        this.searchCounter = 0;
        // Perf counters (read by the benchmark harness): areaRequests = tiles
        // actually generated by a worker; areaDone = results delivered.
        this.stats = { areaRequests: 0, areaDone: 0 };
        // Notified whenever the worker pool is torn down and respawned, so tile
        // consumers can drop their in-flight bookkeeping and re-request.
        this.resetListeners = [];
        // Compile the WASM once for the whole pool (shared across workers) and
        // hand each worker the compiled module, so we pay one compile, not N.
        this._cacheBust = new URLSearchParams((path.split('?')[1]) || '').get('v');
        this._modulePromise = this._compileModule();
        this._spawnWorkers();
        this.getColors();
    }

    // Fetch + compile api.wasm once. Resolves to a WebAssembly.Module, or null on
    // failure (workers then fall back to compiling it themselves).
    _compileModule() {
        const wasmUrl = this.path.replace(/worker\.js/, 'api.wasm');
        const viaBuffer = () => fetch(wasmUrl).then((r) => r.arrayBuffer()).then((b) => WebAssembly.compile(b));
        const compile = (typeof WebAssembly.compileStreaming === 'function')
            ? WebAssembly.compileStreaming(fetch(wasmUrl)).catch(viaBuffer)
            : viaBuffer();
        return compile.catch(() => null);
    }

    addResetListener(fn) { this.resetListeners.push(fn); }
    removeResetListener(fn) { this.resetListeners = this.resetListeners.filter(f => f !== fn); }
    _notifyReset() { for (const fn of this.resetListeners) fn(); }

    getAreaKey(mcVersion, seed, startX, startY, widthX, widthY, dimension, yHeight) {
        return mcVersion + "-" + seed + "-" + startX + "-" + startY + "-" + widthX + "-" + widthY + "-" + dimension + "-" + yHeight;
    }

    // Request the biome data for one world-aligned tile. The callback receives
    // { rgba, ids } (transferables built in the worker). Duplicate in-flight
    // requests for the same tile are dropped - the single caller (DrawSeed) also
    // dedups, so this only guards races (e.g. after a worker restart).
    draw(mcVersion, seed, startX, startY, widthX, widthY, dimension, yHeight, callback) {
        const key = this.getAreaKey(mcVersion, seed, startX, startY, widthX, widthY, dimension, yHeight);
        if (this.inFlight.has(key)) return;
        this.inFlight.add(key);
        const job = { key, mcVersion, seed, startX, startY, widthX, widthY, dimension, yHeight, callback };
        const worker = this._freeWorker();
        if (worker) {
            this._dispatchDraw(worker, job);
        } else {
            this.pending.push(job);
        }
    }

    _freeWorker() {
        for (const worker of this.workers) {
            if (!worker.busy) return worker;
        }
        return null;
    }

    _dispatchDraw(worker, job) {
        this.stats.areaRequests++;
        worker.busy = true;
        worker.job = job;
        worker.callback = job.callback;
        worker.postMessage({
            kind: "GET_AREA",
            data: {
                mcVersion: job.mcVersion, seed: job.seed,
                startX: job.startX, startY: job.startY,
                widthX: job.widthX, widthY: job.widthY,
                dimension: job.dimension, yHeight: job.yHeight
            }
        });
    }

    // Drain queued tile jobs onto any workers that just became free.
    _drainPending() {
        while (this.pending.length > 0) {
            const worker = this._freeWorker();
            if (!worker) return;
            this._dispatchDraw(worker, this.pending.shift());
        }
    }

    // A worker just became free: tiles first (the map must keep painting), then high
    // and low requests, then the search takes whatever is left within its reservation.
    // Every DONE_* branch ends here - otherwise a search whose workers were all lent to
    // tiles (N = 1, or a burst of tiles) would never be handed its next shard.
    _workerFreed() {
        this._drainPending();
        this._drainRequests();
        this._dispatchShards();
    }

    /**
     * Run one engine query on the pool. `kind` is a worker message kind
     * (SEED_SUMMARY, NEAREST_STRUCTURES, GET_SPAWN, …); `data` is posted with a
     * `requestId` added, and the reply is the worker's next `DONE_<kind>` message
     * (matched per worker, since the legacy kinds do not echo `requestId`).
     *
     * Priorities - the order a free worker is handed work: GET_AREA tiles, then 'high'
     * requests, then 'low' requests, then search shards. 'high' is uncapped (short
     * queries the map itself needs). 'low' (the default: dashboard sections) runs on at
     * most max(1, min(2, N - 1)) workers at once, N = pool size, so low requests never
     * occupy every worker and a tile waits at most for one job. A `wide` low request
     * (short slices of one big job: the finder's thumbnail strips) may use up to
     * max(1, N - 1) workers, still leaving one for tiles. During a search the worker(s)
     * the search reserves serve tiles and requests.
     *
     * Resolves with the reply data minus `requestId`, `error` included: an engine error
     * (`{ code, message }`) is an answer about the world, not a failure. A worker that
     * crashes while running the request resolves it with
     * `{ error: { code: 'WORKER_CRASH', message } }`; one made after the whole pool died
     * (see _poolDead) resolves with that error at once. Rejects only when no answer will
     * ever come: `{ cancelled: true, reason: 'cancelled' }` after cancelToken(token), `{ cancelled: true, reason: 'killed' }` after killAll().
     * Callers that may be cancelled must handle the rejection.
     *
     * options = { priority = 'low' | 'high', token = null, wide = false } - `token` (any
     * value compared with ===, e.g. a string or a Symbol per seed) groups requests for
     * cancelToken(); `wide` lifts a low request's cap to N - 1 (see above).
     */
    request(kind, data = {}, { priority = 'low', token = null, wide = false } = {}) {
        return new Promise((resolve, reject) => {
            if (this.poolError) {
                resolve({ error: this.poolError });
                return;
            }
            const id = ++this._requestCounter;
            const entry = { id, kind, data, priority, token, wide, resolve, reject, cancelled: false };
            (priority === 'high' ? this.highQueue : this.lowQueue).push(entry);
            this._drainRequests();
        });
    }

    /**
     * One biome area off the tile path, e.g. the Biomes section's 500×500-cell tally
     * (~0.7 s on 26.3). It is request('GET_AREA', params, low) and never touches the tile
     * machinery (no `inFlight` key, no `stats.areaDone`): its DONE_GET_AREA is matched by
     * the request branch of _commonListener, which runs before the tile one.
     *
     * params = { mcVersion, seed, startX, startY, widthX, widthY, dimension, yHeight }
     * in the worker's names and 1:4 cells (startY / widthY are the Z axis).
     * Resolves with `{ ...params echoed, rgba, ids }`, ids row-major [row * widthX + col].
     * `wide`: see request().
     */
    requestArea(params, { token = null, wide = false } = {}) {
        return this.request('GET_AREA', params, { priority: 'low', token, wide });
    }

    /**
     * Drop every request made with `token` (e.g. the dashboard's queries for a seed the
     * user just left): queued ones are removed and never posted, in-flight ones are
     * rejected at once and their late reply is discarded (the worker is freed when it
     * arrives - a worker inside a synchronous C call cannot be interrupted). Each
     * promise rejects with `{ cancelled: true, reason: 'cancelled' }`.
     */
    cancelToken(token) {
        if (token == null) return;
        const reason = { cancelled: true, reason: 'cancelled' };
        for (const queue of [this.highQueue, this.lowQueue]) {
            for (let i = queue.length - 1; i >= 0; i--) {
                if (queue[i].token !== token) continue;
                const [entry] = queue.splice(i, 1);
                entry.reject(reason);
            }
        }
        for (const worker of this.workers) {
            const entry = worker.request;
            if (entry && !entry.cancelled && entry.token === token) {
                entry.cancelled = true;
                entry.reject(reason);
            }
        }
    }

    _lowCap(entry) {
        const spare = Math.max(1, this.numberOfWorkers - 1);
        return entry?.wide ? spare : Math.min(2, spare);
    }

    // Counted from the workers rather than kept in a counter, so a terminated or
    // replaced worker can never leave the count drifting.
    _lowInFlight() {
        return this.workers.filter((w) => w.request?.priority === 'low').length;
    }

    // Hand queued requests to free workers: high first, low within the cap.
    _drainRequests() {
        for (;;) {
            if (this.highQueue.length === 0 && this.lowQueue.length === 0) return;
            const worker = this._freeWorker();
            if (!worker) return;
            let entry = this.highQueue.shift();
            if (!entry) {
                if (this._lowInFlight() >= this._lowCap(this.lowQueue[0])) return;
                entry = this.lowQueue.shift();
            }
            worker.busy = true;
            worker.request = entry;
            worker.postMessage({ kind: entry.kind, data: { ...entry.data, requestId: entry.id } });
        }
    }

    /**
     * Start a streaming seed search across the worker pool. Returns
     * `{ id, stop }`; `stop()` ends this search (and only this one) as 'stopped'.
     * Throws when a search is already running - call stopSearch() first.
     *
     * criteria = {
     *   mcVersion,            VERSIONS int
     *   dimension = 0,        0 Overworld, -1 Nether, 1 End; every criterion must generate there
     *   yHeight = 256,        Y at which biomes are sampled (matters from 1.18)
     *   biomes = [],          BiomeID ints, ALL required inside the box at yHeight
     *   anyBiomes = [],       BiomeID ints, at least ONE of them inside the box at yHeight
     *   excludeBiomes = [],   BiomeID ints, NONE of them anywhere in the box at yHeight
     *   structures = [],      StructureType ints, ALL required inside the box
     *   rangeBlocks,          block half-width: the box is [-range, +range]²
     *   startingSeed = 0n,    BigInt or decimal string (never a Number): the first candidate
     *   count,                hits wanted; the search ends with 'target' when reached (>= 1)
     *   maxSeedsToScan?,      BigInt cap on candidates; defaults to, and never exceeds, DEFAULT_MAX_SCAN
     * }
     *
     * Candidate space: [start, end), end = start + min(maxSeedsToScan, DEFAULT_MAX_SCAN, room).
     *   - structure modes: a candidate is a lower-48 family (all 65 536 seeds sharing the
     *     layout, one hit per family); start = startingSeed & MASK48, room ends at 2^48.
     *   - biome-only: a candidate is one signed 64-bit seed; room ends at 2^63.
     * Shards: consecutive [nextShard, nextShard + shardLen) ranges (shardLenFor ≈ 1 s of
     * work) are dealt in order to free, loaded workers - at most max(1, N-1) at a time,
     * so one worker always stays available for GET_AREA tiles, and tiles are drained
     * before shards whenever a worker frees up. Workers that finish loading later are
     * given shards too. Each shard's maxResults is the remaining count.
     *
     * Callbacks (optional; called synchronously from worker message handlers):
     *   onHit({ seed: BigInt, spawnX, spawnZ, structures: [{ type, x, z }], index, examined, tested })
     *       once per distinct seed (deduped by String(seed) - a guard only, shards are
     *       disjoint); `index` is the hit's position in the results list.
     *   onProgress({ examined: BigInt, tested: Number, hits: Number, elapsedMs: Number })
     *       monotonic: completed shards plus the live shards' latest counters. Driven by
     *       SEED_UPDATE (time-paced by the engine, ≤ ~10/s per worker), by SEED_FOUND and by
     *       DONE_FIND_SEEDS, so shards too short to tick still count. `examined` are
     *       candidates (seeds or families) consumed, `tested` full 64-bit seeds generated
     *       - derive seeds/s from `tested`, progress from `examined`.
     *   onDone(hits, examined: BigInt, reason, resumeSeed: BigInt, { tested, elapsedMs, error })
     *       exactly once. reason: 'target' (count reached) | 'exhausted' (the whole
     *       candidate space was scanned) | 'stopped' (stop()/stopSearch()/killAll()) |
     *       'error' (the engine rejected the criteria, error = { code, message }, see
     *       FIND_SEEDS_ERRORS in public/workers/seeder.js - never thrown; or a shard's
     *       worker crashed twice, or the pool is dead, code 'WORKER_CRASH'). error is
     *       null otherwise.
     *
     * resumeSeed is the start of the first shard never handed out: resuming a search there
     * is duplicate-free because shards are disjoint and dealt in order. The unexamined
     * tails of shards still running when the search ended ('target', 'stopped') are
     * skipped - at most maxWorkers × shardLen candidates; the finder shows resumeSeed as
     * the "start" of "Find more" for that reason. On 'exhausted' resumeSeed === end.
     *
     * Ending a search terminates only the workers running shards (a worker inside the
     * synchronous C loop cannot see a message) and respawns them at once: STOP is
     * instantaneous, the module is precompiled, and the reserved worker and its tiles
     * are untouched - no reset notification is sent.
     */
    findSeeds(criteria, { onHit, onProgress, onDone } = {}) {
        if (this.search?.active) {
            throw new Error('QueueManager.findSeeds: a search is already running; call stopSearch() first.');
        }
        const biomes = criteria.biomes ?? [];
        const anyBiomes = criteria.anyBiomes ?? [];
        const excludeBiomes = criteria.excludeBiomes ?? [];
        const structures = criteria.structures ?? [];
        const mode = structures.length > 0 ? 'struct' : 'biome';
        const requested = BigInt(criteria.startingSeed ?? 0);
        const start = mode === 'struct' ? (requested & MASK48) : BigInt.asIntN(64, requested);
        const spaceEnd = mode === 'struct' ? FAMILY_SPACE_END : SEED_SPACE_END;
        const wanted = criteria.maxSeedsToScan == null ? DEFAULT_MAX_SCAN : BigInt(criteria.maxSeedsToScan);
        const room = bigMin(wanted, DEFAULT_MAX_SCAN, spaceEnd - start);
        const end = start + (room > 0n ? room : 0n);
        const count = Number(criteria.count);
        const target = Number.isFinite(count) && count >= 1 ? Math.floor(count) : 1;
        const id = ++this.searchCounter;
        this.search = {
            id, mode, start, end, target,
            criteria: { ...criteria, biomes, anyBiomes, excludeBiomes, structures, dimension: criteria.dimension ?? 0, yHeight: criteria.yHeight ?? 256 },
            nextShard: start,
            retry: [],                 // shards whose worker crashed, dealt again before new ones
            shardLen: BigInt(shardLenFor({ ...criteria, structures })),
            shardCounter: 0,
            hits: [],
            seen: new Set(),
            completedExamined: 0n,
            completedTested: 0,
            live: new Map(),           // worker -> shard it is running
            maxWorkers: Math.max(1, this.numberOfWorkers - 1),
            active: true,
            startedAt: performance.now(),
            onHit, onProgress, onDone,
        };
        const dead = this.poolError;
        if (end <= start || dead) {
            // Nothing to scan (the start sits at the top of the space), or no worker will
            // ever run a shard (a dead pool): report it, but asynchronously so the caller
            // holds the handle before onDone fires.
            queueMicrotask(() => { if (this.search?.id === id) this._finish(dead ? 'error' : 'exhausted', dead); });
        } else {
            this._dispatchShards();
        }
        return { id, stop: () => { if (this.search?.id === id) this._finish('stopped'); } };
    }

    // End the active search as 'stopped' (instant: see findSeeds). No-op when idle.
    stopSearch() {
        this._finish('stopped');
    }

    get searching() {
        return !!this.search?.active;
    }

    // Deal the next shards to free workers, within the reservation.
    _dispatchShards() {
        const s = this.search;
        if (!s?.active) return;
        while ((s.retry.length > 0 || s.nextShard < s.end) && s.live.size < s.maxWorkers) {
            const worker = this._freeWorker();
            if (!worker) return;
            let shard = s.retry.shift();
            if (!shard) {
                const len = bigMin(s.shardLen, s.end - s.nextShard);
                shard = { searchId: s.id, shardId: `${s.id}-${s.shardCounter++}`, start: s.nextShard, len, examined: 0, tested: 0 };
                s.nextShard += len;
            }
            worker.busy = true;
            worker.shard = shard;
            s.live.set(worker, shard);
            const c = s.criteria;
            worker.postMessage({
                kind: 'FIND_SEEDS',
                data: {
                    shardId: shard.shardId,
                    mcVersion: c.mcVersion, dimension: c.dimension, yHeight: c.yHeight,
                    biomes: c.biomes, anyBiomes: c.anyBiomes, excludeBiomes: c.excludeBiomes,
                    structures: c.structures, rangeBlocks: c.rangeBlocks,
                    startingSeed: String(BigInt.asIntN(64, shard.start)),
                    maxSeedsToScan: Number(shard.len),
                    maxResults: Math.max(1, s.target - s.hits.length),
                },
            });
        }
    }

    // Is this message about a shard of the active search? (Late messages from a
    // replaced worker, or from a shard of a finished search, are ignored.)
    _shardOf(worker) {
        const s = this.search;
        const shard = worker.shard;
        return (s?.active && shard && shard.searchId === s.id) ? shard : null;
    }

    _onShardProgress(worker, data) {
        const shard = this._shardOf(worker);
        if (!shard) return;
        shard.examined = Math.max(shard.examined, data.examined);
        shard.tested = Math.max(shard.tested, data.tested);
        this._progress();
    }

    _onShardHit(worker, data) {
        const s = this.search;
        const shard = this._shardOf(worker);
        if (!shard) return;
        shard.examined = Math.max(shard.examined, data.examined);
        shard.tested = Math.max(shard.tested, data.tested);
        const key = String(data.seed);
        if (!s.seen.has(key)) {
            s.seen.add(key);
            const hit = { ...data, index: s.hits.length };
            s.hits.push(hit);
            s.onHit?.(hit);
        }
        // A callback may have stopped the search meanwhile.
        if (!s.active) return;
        this._progress();
        if (s.active && s.hits.length >= s.target) this._finish('target');
    }

    _onShardDone(worker, data) {
        const s = this.search;
        const shard = this._shardOf(worker);
        this._cleanWorker(worker);
        if (shard && data.shardId === shard.shardId) {
            s.live.delete(worker);
            s.completedExamined += BigInt(data.examined);
            s.completedTested += data.tested;
            this._progress();
            if (s.active && data.error) this._finish('error', data.error);
        }
        this._drainPending();
        this._drainRequests();
        const cur = this.search;
        if (cur?.active) {
            if (cur.retry.length > 0 || cur.nextShard < cur.end) this._dispatchShards();
            else if (cur.live.size === 0) this._finish('exhausted');
        }
    }

    _totals(s) {
        let examined = s.completedExamined;
        let tested = s.completedTested;
        for (const shard of s.live.values()) {
            examined += BigInt(shard.examined);
            tested += shard.tested;
        }
        return { examined, tested, hits: s.hits.length, elapsedMs: performance.now() - s.startedAt };
    }

    _progress() {
        const s = this.search;
        if (!s?.active || !s.onProgress) return;
        s.onProgress(this._totals(s));
    }

    // End the active search. Workers still running a shard are terminated and
    // respawned (unless killAll() is about to tear the whole pool down anyway), then
    // onDone runs. Also on 'error', so that after onDone no worker of this search is
    // still running.
    _finish(reason, error = null, { replaceWorkers = true } = {}) {
        const s = this.search;
        if (!s?.active) return;
        s.active = false;
        const { examined, tested, elapsedMs } = this._totals(s);
        const resumeSeed = s.nextShard;
        const victims = [...s.live.keys()];
        s.live.clear();
        this.search = null;
        if (replaceWorkers && victims.length > 0) this._replaceWorkers(victims);
        s.onDone?.(s.hits, examined, reason, resumeSeed, { tested, elapsedMs, error });
        this._drainPending();
        this._drainRequests();
    }

    // Terminate these workers (blocked in the C loop and unable to be asked to stop, or
    // crashed) and spawn one replacement each. Their jobs are the caller's business, so
    // reset listeners are NOT notified.
    _replaceWorkers(list) {
        for (const worker of list) {
            worker.dead = true;
            worker.terminate();
            this.booting.delete(worker);
            const i = this.workers.indexOf(worker);
            if (i >= 0) this.workers.splice(i, 1);
            this._spawnWorker((w) => this.workers.push(w));
        }
    }

    // Delegates to request() (high priority); `callback(x, z)`, or `onError(error)` when
    // the engine could not answer (an engine error or WORKER_CRASH). Neither is called if
    // the pool is torn down first.
    findSpawn(mcVersion, seed, callback, onError) {
        this.request('GET_SPAWN', { mcVersion, seed }, { priority: 'high' })
            .then(({ x, z, error }) => { if (error) onError?.(error); else callback(x, z); })
            .catch(() => {});
    }

    // Delegates to request() (high priority); `callback({ coords })`.
    findStrongholds(mcVersion, seed, howMany, callback) {
        this.request('GET_STRONGHOLDS', { mcVersion, seed, howMany }, { priority: 'high' })
            .then((data) => { if (!data.error) callback(data); })
            .catch(() => {});
    }

    // Delegates to request() (high priority); `callback({ coords })`.
    getStructuresInRegions(mcVersion, structType, seed, regionsRange, dimension, callback) {
        this.request('GET_STRUCTURES_IN_REGIONS', { mcVersion, structType, seed, regionsRange, dimension }, { priority: 'high' })
            .then((data) => { if (!data.error) callback(data); })
            .catch(() => {});
    }

    /**
     * What the engine supports on one version, for gating the finder's criteria and
     * presets. Resolves with DONE_GET_VERSION_SUPPORT's data:
     * `{ mcVersion, newest, biomes: [ids that exist], biomeDimensions: { id: dim },
     *    structures: { type: dim | -100 }, regionBlocks: { type: n }, minDistance: { type: n } }`.
     * Delegates to request() (high priority): queued until a worker is free, and it
     * rejects only when the pool is torn down (`{ cancelled: true, reason: 'killed' }`).
     */
    getVersionSupport(mcVersion, biomeIds = [], structTypes = []) {
        return this.request('GET_VERSION_SUPPORT', { mcVersion, biomeIds, structTypes }, { priority: 'high' });
    }

    // Delegates to request() (high priority). Called by the constructor before any
    // worker exists: the request just waits in the queue for the first DONE_LOADING.
    getColors() {
        this.request('GET_COLORS', {}, { priority: 'high' })
            .then(({ colors, error }) => { if (!error) this.COLORS = colors; })
            .catch(() => {});
    }

    // Tear down the whole pool. A running search ends as 'stopped' first; its shard
    // workers go down with the rest (no replacements are spawned). Every queued or
    // in-flight request rejects with { cancelled: true, reason: 'killed' }.
    killAll() {
        this._finish('stopped', null, { replaceWorkers: false });
        const killed = { cancelled: true, reason: 'killed' };
        for (const entry of [...this.highQueue, ...this.lowQueue]) entry.reject(killed);
        this.highQueue = [];
        this.lowQueue = [];
        for (const worker of this.workers) {
            if (worker.request && !worker.request.cancelled) worker.request.reject(killed);
            worker.request = null;
        }
        for (const worker of this.workers) {
            worker.dead = true;
            worker.terminate();
        }
        for (const worker of this.booting) {
            worker.dead = true;
            worker.terminate();
        }
        this.booting.clear();
        this.workers = [];
        this.pending = [];
        this.inFlight.clear();
        this._notifyReset();
    }

    restartAll() {
        this.killAll();
        // A fresh pool: a dead one gets its boot attempts back.
        this.poolError = null;
        this.bootFailures = 0;
        this._spawnWorkers();
        // The palette request may have died with the old pool (killed before it loaded).
        if (this.COLORS === null) this.getColors();
    }

    _spawnWorkers() {
        for (let i = 0; i < this.numberOfWorkers; i++) {
            this._spawnWorker((w) => {
                this.workers.push(w);
            });
        }
    }

    _spawnWorker(callback) {
        const worker = new Worker(this.path);
        worker.name = "Worker_" + this.workerCounter++;
        worker.busy = true;
        worker.job = null;
        worker.shard = null;
        worker.request = null;
        worker.dead = false;
        this.booting.add(worker);
        worker.addEventListener('message', (e) => this._commonListener(e, worker, callback));
        worker.addEventListener('error', (e) => this._onWorkerCrash(e, worker));
        worker.addEventListener('messageerror', (e) => this._onWorkerCrash(e, worker));
        // Boot the worker once the shared module is ready (module may be null →
        // the worker compiles api.wasm itself).
        this._modulePromise.then((module) => worker.postMessage({ kind: 'INIT', module }));
    }

    _commonListener(e, worker, callback) {
        // A terminated worker's already-queued messages: nothing to do with them.
        if (worker.dead) return;
        if (e.data.kind === "DONE_LOADING") {
            this.booting.delete(worker);
            this.bootFailures = 0;
            worker.busy = false;
            callback(worker);
            this._workerFreed();
        }
        // Requests are matched before tiles: a GET_AREA posted through request() (see
        // requestArea) answers with DONE_GET_AREA too, and must resolve its promise instead
        // of going through the tile bookkeeping. A tile-dispatched worker has no `request`
        // (the two never share a worker), so tiles still take the branch below.
        else if (worker.request && e.data.kind === 'DONE_' + worker.request.kind) {
            // A worker runs one request at a time, so its reply is the next DONE_<kind>
            // it posts. The legacy kinds (GET_AREA included) echo no requestId; the
            // dashboard kinds must echo ours.
            const req = worker.request;
            const { requestId, ...result } = e.data.data ?? {};
            if (requestId !== undefined && requestId !== req.id) return;
            this._cleanWorker(worker);
            if (!req.cancelled) req.resolve(result);
            this._workerFreed();
        }
        else if (e.data.kind === "DONE_GET_AREA") {
            this.stats.areaDone++;
            const data = e.data.data;
            const job = worker.job;
            this.inFlight.delete(job ? job.key : this.getAreaKey(data.mcVersion, data.seed, data.startX, data.startY, data.widthX, data.widthY, data.dimension, data.yHeight));
            const cb = worker.callback;
            this._cleanWorker(worker);
            // A tile the engine failed to generate is skipped: retrying would fail the same way.
            if (cb && !data.error) cb({ rgba: data.rgba, ids: data.ids });
            this._workerFreed();
        }
        else if (e.data.kind === "SEED_UPDATE") {
            this._onShardProgress(worker, e.data.data);
        }
        else if (e.data.kind === "SEED_FOUND") {
            this._onShardHit(worker, e.data.data);
        }
        else if (e.data.kind === "DONE_FIND_SEEDS") {
            this._onShardDone(worker, e.data.data);
        }
    }

    // A worker died: an uncaught exception (a failed importScripts or instantiate, a WASM
    // trap, which worker.js lets escape without replying) or a reply that could not be
    // deserialized. It is replaced, and its job is failed or dealt again: a tile and a
    // search shard get one more try on another worker, a request resolves with a
    // WORKER_CRASH error (an answer, like an engine error: request() still rejects only on
    // cancel or kill), and a shard that crashes twice ends the search with reason 'error'.
    _onWorkerCrash(e, worker) {
        if (worker.dead) return;
        e.preventDefault?.();
        const message = `The engine worker crashed${e.message ? `: ${e.message}` : '.'}`;
        console.warn(`QueueManager: ${worker.name}: ${message}`);
        const { job, request, shard } = worker;
        this._cleanWorker(worker);
        if (this.booting.has(worker) && ++this.bootFailures > MAX_BOOT_FAILURES) {
            worker.dead = true;
            worker.terminate();
            this.booting.delete(worker);
        } else {
            this._replaceWorkers([worker]);
        }
        if (job) {
            if (job.retried) this.inFlight.delete(job.key);
            else this.pending.unshift({ ...job, retried: true });
        }
        if (request && !request.cancelled) request.resolve({ error: crashError(message) });
        const s = this.search;
        if (shard && s?.active && shard.searchId === s.id) {
            s.live.delete(worker);
            if (shard.retried) this._finish('error', crashError(message));
            else s.retry.push({ ...shard, retried: true, examined: 0, tested: 0 });
        }
        if (this.workers.length === 0 && this.booting.size === 0) this._poolDead(message);
        this._workerFreed();
    }

    // No worker is left and none is booting (every one crashed while booting): nothing
    // will ever answer, so everything waiting is failed with WORKER_CRASH, and so is
    // everything asked later (request() and findSeeds() check poolError) until restartAll().
    _poolDead(message) {
        const error = crashError(message);
        this.poolError = error;
        this._finish('error', error, { replaceWorkers: false });
        for (const entry of [...this.highQueue, ...this.lowQueue]) entry.resolve({ error });
        this.highQueue = [];
        this.lowQueue = [];
        this.pending = [];
        this.inFlight.clear();
    }

    _cleanWorker(worker) {
        worker.callback = null;
        worker.job = null;
        worker.shard = null;
        worker.request = null;
        worker.busy = false;
    }
}
